def _gloss(x: str) -> tuple[str, bool]:
    """对片段做词表替换；返回 (译文, 是否完全覆盖)。"""
    zh = x.lower().strip()
    for term in sorted(GLOSSARY, key=len, reverse=True):
        zh = re.sub(rf"\b{re.escape(term)}\b", GLOSSARY[term], zh)
    # 剩余英文词（去停用词）
    leftover = [w for w in re.findall(r"[a-z][a-z0-9\-]*", zh)
                if w not in {"and", "or", "of", "the", "in", "by", "a", "an", "to",
                             "type", "like", "mediated", "dependent", "independent",
                             "associated", "related", "specific", "family", "superfamily"}]
    return zh, not leftover


