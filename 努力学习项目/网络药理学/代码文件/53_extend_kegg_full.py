def translate(en: str) -> tuple[str, bool]:
    """返回 (中文名, 是否高置信)。"""
    low = en.lower().strip()
    if low in OVERRIDES:
        return OVERRIDES[low], True
    # 句型模板作用于英文原串
    for pat, tmpl in PATTERNS:
        m = re.match(pat, low)
        if m:
            head = m.group(1)
            zh_head, full = _gloss(head)
            zh = re.sub(pat, lambda _: tmpl.replace(r"\1", zh_head), low)
            zh = re.sub(r"\band\b", "与", zh)
            zh = re.sub(r"\bor\b", "或", zh)
            zh = re.sub(r"\bof\b", "", zh)
            return zh, full
    # 无句型：整串词表替换
    zh, full = _gloss(low)
    if zh != low:
        return zh, full
    return en, False


def _tidy(zh: str) -> str:
    """中文名排版清理：去 CJK 邻接空格、逗号改顿号。"""
    zh = re.sub(r"(?<=[\u4e00-\u9fff）])\s+(?=[\u4e00-\u9fffA-Za-z0-9（])", "", zh)
    zh = re.sub(r"(?<=[A-Za-z0-9）])\s+(?=[\u4e00-\u9fff])", "", zh)
    zh = re.sub(r"(?<=[\u4e00-\u9fff]),\s*", "、", zh)
    return zh


def fname_en(en: str) -> str:
    s = re.sub(r"[^A-Za-z0-9\- ]", "", en).replace(" ", "_")
    return re.sub(r"_+", "_", s)


def main():
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry", action="store_true", help="只打印不写表/不下载")
    args = ap.parse_args()

    s = requests.Session()
    s.trust_env = False
    s.headers.update({"User-Agent": "Mozilla/5.0"})

    # 官方列表
    official = {}
    r = s.get("https://rest.kegg.jp/list/pathway/hsa", timeout=60)
    r.raise_for_status()
    for line in r.text.splitlines():
        pid, name = line.split("\t", 1)
        official[pid.replace("path:", "")] = name.split(" - Homo sapiens")[0]
    r2 = s.get("https://rest.kegg.jp/list/pathway", timeout=60)
    r2.raise_for_status()
    for line in r2.text.splitlines():
        pid, name = line.split("\t", 1)
        official[pid.replace("path:", "")] = name

    # 现有映射表
    wb = load_workbook(XLSX)
    ws = wb.active
    rows = list(ws.iter_rows(values_only=True))
    header = rows[0]
    i_rank = header.index("排名")
    existing = {r[header.index("KEGG编号")] for r in rows[1:]}
    max_rank = max(int(r[i_rank]) for r in rows[1:] if r[i_rank] is not None)

    # 1) hsa 未覆盖
    hsa_new = [pid for pid in official if pid.startswith("hsa") and pid not in existing]
    # 2) map 未覆盖（hsa 无对应 5 位数字）
    hsa_codes = {pid[3:] for pid in official if pid.startswith("hsa")}
    map_new = []
    for pid in official:
        if not pid.startswith("map"):
            continue
        code = pid[3:]
        if code in hsa_codes:
            continue
        # 代谢/次生代谢相关：编号 <01000 或 010xx/011xx
        if code < "01000" or code.startswith("010") or code.startswith("011"):
            map_new.append(pid)
    print(f"hsa 新增 {len(hsa_new)} 条，map 新增 {len(map_new)} 条", flush=True)

    added = 0
    low_conf = []
    for pid in hsa_new + map_new:
        en = official[pid]
        if pid in ID_OVERRIDES:
            zh, ok = ID_OVERRIDES[pid], True
        else:
            zh, ok = translate(en)
        zh = _tidy(zh)
        if not ok:
            low_conf.append((pid, en))
        max_rank += 1
        fen = fname_en(en)
        png = f"{max_rank:03d}_{pid}_{fen}.png"
        gif = f"{max_rank:03d}_{pid}_{zh}_{fen}_动画.gif"
        url = f"https://rest.kegg.jp/get/{pid}/image"
        if not args.dry:
            ws.append([max_rank, pid, zh, en, "待绘制", gif, png, url])
        existing.add(pid)
        added += 1

        dest = OUT / png
        if not args.dry and not dest.exists():
            try:
                rr = s.get(url, timeout=60)
                rr.raise_for_status()
                if rr.content.startswith(b"\x89PNG"):
                    dest.write_bytes(rr.content)
                    print(f"[png] {png} {len(rr.content)//1024}KB", flush=True)
            except Exception as e:
                print(f"[png-fail] {pid} {e}", flush=True)
            time.sleep(0.4)
        print(f"[add] {max_rank} {pid} {zh} / {en}", flush=True)

    if added and not args.dry:
        wb.save(XLSX)
    print(f"done: added={added}, total={max_rank}{' (dry)' if args.dry else ''}", flush=True)
    if low_conf:
        print("低置信度中文名（需人工核）：", flush=True)
        for pid, en in low_conf:
            print(f"  {pid}: {en}", flush=True)


if __name__ == "__main__":
    main()
